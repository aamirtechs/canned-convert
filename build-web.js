import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Mini-bundler: wraps every src/ module in a CommonJS-style define() and emits
// docs/app.js with a tiny require shim, so the browser app runs the exact same
// code as the library and CLI. The sources are ES modules, so import and
// export statements are rewritten to the shim while bundling. No dependencies,
// no build tooling beyond Node. Adapted from the sku-shifter build-web.js.

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(ROOT, "src");
const OUT = path.join(ROOT, "docs", "app.js");
const EXCLUDE = new Set(["cli.js"]);
const ENTRY = "src/convert";
const GLOBAL_NAME = "CannedConvert";

function collect(dir, base) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...collect(full, base));
    else if (entry.name.endsWith(".js") && !EXCLUDE.has(entry.name)) {
      const key = path.relative(base, full).replace(/\\/g, "/").replace(/\.js$/, "");
      out.push({ key, code: fs.readFileSync(full, "utf8") });
    }
  }
  return out.sort((a, b) => a.key.localeCompare(b.key));
}

function transform(code) {
  const exported = [];
  let out = code;
  out = out.replace(/export\s+\*\s+from\s+["']([^"']+)["'];?/g,
    (m, req) => "Object.assign(module.exports, require(" + JSON.stringify(req) + "));");
  out = out.replace(/import\s*\{([^}]+)\}\s*from\s+["']([^"']+)["'];?/g,
    (m, names, req) => "const {" + names + "} = require(" + JSON.stringify(req) + ");");
  out = out.replace(/import\s+["']([^"']+)["'];?/g,
    (m, req) => "require(" + JSON.stringify(req) + ");");
  out = out.replace(/export\s+(async\s+function|function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/g,
    (m, kind, name) => { exported.push(name); return kind + " " + name; });
  out = out.replace(/export\s*\{([^}]+)\};?/g, (m, names) =>
    names.split(",").map((s) => s.trim()).filter(Boolean).map((s) => {
      const parts = s.split(/\s+as\s+/);
      const local = parts[0].trim();
      const pub = (parts[1] || parts[0]).trim();
      return "module.exports." + pub + " = " + local + ";";
    }).join("\n"));
  if (exported.length) {
    out += "\n" + exported.map((n) => "module.exports." + n + " = " + n + ";").join("\n") + "\n";
  }
  return out;
}

const modules = collect(SRC, SRC).map(({ key, code }) => ({ key: "src/" + key, code: transform(code) }));

const header = "/* canned-convert browser bundle. Generated by build-web.js from src/. Do not edit by hand. */\n'use strict';\n";
const shim = `
const __modules = {};
const __cache = {};
function __define(key, fn) { __modules[key] = fn; }
function __resolve(fromKey, request) {
  const parts = fromKey.split('/').slice(0, -1);
  for (const seg of request.split('/')) {
    if (seg === '.' || seg === '') continue;
    else if (seg === '..') parts.pop();
    else parts.push(seg);
  }
  return parts.join('/').replace(/\\.js$/, '');
}
function __load(key) {
  if (key.startsWith('node:')) key = '__node/' + key.slice(5);
  if (__cache[key]) return __cache[key].exports;
  const module = { exports: {} };
  __cache[key] = module;
  const localRequire = (request) => __load(request.startsWith('node:') ? request : __resolve(key, request));
  __modules[key](module, module.exports, localRequire);
  return module.exports;
}
__define('__node/fs', function(module, exports, require) {
  function unavailable(name) {
    return function () { throw new Error(name + ' is not available in the browser bundle. File access stays in the CLI; the web app works on in-page data instead.'); };
  }
  module.exports = { readFileSync: unavailable('readFileSync'), writeFileSync: unavailable('writeFileSync'), mkdirSync: unavailable('mkdirSync') };
});
`;
const body = modules.map(({ key, code }) =>
  "__define(" + JSON.stringify(key) + ", function(module, exports, require) {\n" + code + "\n});"
).join("\n");
