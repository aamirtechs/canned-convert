const footer = "\nwindow." + GLOBAL_NAME + " = __load(ENTRY_PLACEHOLDER);\n" + EXTRA_CODE;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + shim + body + footer.replace("ENTRY_PLACEHOLDER", JSON.stringify(ENTRY)), "utf8");
